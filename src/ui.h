/* ui.h —— 界面宿主层(可替换的实现)。
 *
 * 界面本身是 ui/ 目录下的普通网页,由内置 HTTP 服务提供。这一层只做一件事:
 * **把这个网页显示出来**。当前用系统 Edge/Chrome 的 --app 应用窗口(无地址栏),
 * 找不到 Chromium 才退回默认浏览器。
 *
 * 为什么不内嵌浏览器控件:本机实测 WebView2 嵌入模式能创建环境对象、但渲染进程
 * 起不来(约 1.1 秒后整棵树退出),窗口停在纯白。带一个"有时白屏"的运行时依赖
 * 不划算 —— 系统浏览器的 --app 窗口零额外依赖,观感也够用。
 *
 * 下一步(进行中):主界面改成本进程内的原生窗口,网页只作为过渡形态保留。
 */
#ifndef AGENT_UI_H
#define AGENT_UI_H

/* 异步打开界面(内部起线程,立即返回,不阻塞服务)
   port = 后端监听端口 */
void ui_open_url_async(int port);

/* 关掉我们自己打开的那个应用窗口(不动用户原本开着的浏览器) */
void ui_close(void);

/* 界面窗口被关掉时,要不要顺手把服务也停掉。
   有托盘时常驻;--debug 或托盘不可用时按原样退出。 */
void ui_set_stop_on_close(int on);

/* 当前实际生效的显示方式,用于日志/启动横幅 */
const char *ui_mode_name(void);

#endif /* AGENT_UI_H */